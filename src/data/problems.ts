import type { Problem, Segment } from "../lib/types.ts";

function long(id: string, source: string, display: string, parts: string[]): Problem {
  const chars = [...display];
  if (chars.length !== parts.length) {
    throw new Error(`${id}: display ${chars.length} chars != ${parts.length} parts`);
  }
  const segments: Segment[] = chars.map((displayChar, index) => ({
    display: displayChar,
    typing: parts[index]!,
  }));
  return {
    id,
    mode: "long",
    source,
    displayText: display,
    typingText: parts.join(""),
    segments,
  };
}

function code(id: string, source: string, text: string): Problem {
  return {
    id,
    mode: "code",
    source,
    displayText: text,
    typingText: text,
    segments: null,
  };
}

